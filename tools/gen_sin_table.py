#!/usr/bin/env python3
"""Generate core/toy_signal_sin.inc: one full cycle of Q15 sine.

This script runs OFFLINE, once, with native floating point. The
integers it prints are the specification from then on: the C code
never recomputes them, so the table is bit-identical on host,
RP2040/RP2350 and wasm32 by construction (integer constants in
source, the structural-constants exception of docs/CARTRIDGES.md).
Regenerating with different rounding would change every synthetic
stream hash, so treat any regeneration as a signal-format version
bump, never a quiet refresh.

Usage: python tools/gen_sin_table.py > core/toy_signal_sin.inc
"""
import math
import sys

N = 1024  # table steps per cycle; index = phase >> 22


def main() -> int:
    out = sys.stdout
    out.write("/* toy_signal_sin.inc - generated by tools/gen_sin_table.py.\n")
    out.write(" * Q15 sine, one full cycle, 1025 entries (last repeats first\n")
    out.write(" * so interpolation at the wrap needs no branch). Do not edit\n")
    out.write(" * by hand; regeneration is a signal-format version bump. */\n")
    out.write("static const int16_t toy_sig_sin_table[1025] = {\n")
    vals = []
    for i in range(N + 1):
        v = round(math.sin(2.0 * math.pi * (i % N) / N) * 32767.0)
        vals.append(max(-32767, min(32767, v)))
    for row in range(0, len(vals), 8):
        out.write("    " + ", ".join(f"{v:6d}" for v in vals[row:row + 8]) + ",\n")
    out.write("};\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
